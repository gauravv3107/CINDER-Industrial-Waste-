/**
 * Client-side file generation and download utility
 */

/**
 * Trigger download of raw text or blob
 * @param {string} filename
 * @param {string} content
 * @param {string} [mimeType='text/plain']
 */
export function triggerFileDownload(filename, content, mimeType = 'text/plain') {
  const blob = new Blob([content], { type: `${mimeType};charset=utf-8;` });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', filename);
  link.style.visibility = 'hidden';
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Generate and download Executive Performance CSV Report
 * @param {object} kpis
 * @param {Array<object>} pipelineTrades
 */
export function exportExecutiveCsvReport(kpis, pipelineTrades) {
  const lines = [
    'CINDER EXECUTIVE PERFORMANCE REPORT',
    `Generated,${new Date().toISOString()}`,
    'Region,Northern Virginia Industrial Heat Network',
    'Facility ID,ASH-01',
    '',
    'KEY PERFORMANCE INDICATORS',
    'Metric,Value,Period,Delta',
    `Thermal Energy Recaptured,${kpis.thermalRecapturedMWh} MWh,October 2026,+18.6%`,
    `CO2e Avoided,${kpis.co2AvoidedTonnes} tonnes,October 2026,+18.6%`,
    `Active Thermal Trades,${kpis.activeContracts} contracts,October 2026,+3 contracts`,
    `Hardware Value Saved,$${kpis.hardwareSavedUSD.toLocaleString()},October 2026,+12.4%`,
    '',
    'ACTIVE PIPELINE TRADES',
    'UTC Timestamp,Trade Route,Output (MW),Status',
  ];

  pipelineTrades.forEach((trade) => {
    lines.push(`"${trade.utc}","${trade.route}","${trade.outputMW} MW","${trade.status}"`);
  });

  triggerFileDownload('CINDER_Executive_Report_Oct2026.csv', lines.join('\n'), 'text/csv');
}

